package tools

import (
	"fmt"
	"sort"
	"strings"
)

// RegisteredLanguageSupport is the bundled syntax inventory. It is independent
// of user configuration, installed executables, project files and native vaults.
// ParserFixture is enforced by TestLocalLanguageDeclarations for every entry;
// it describes fixture coverage, never universal parsing or semantic correctness.
func RegisteredLanguageSupport() []LanguageSupportEntry {
	names := []string{"go"}
	for name := range localParsers {
		names = append(names, name)
	}
	sort.Strings(names)
	result := make([]LanguageSupportEntry, 0, len(names))
	for _, name := range names {
		parser := name == "go" || localParsers[name] != nil
		result = append(result, LanguageSupportEntry{Language: name, Recognition: true, LocalParser: parser, ParserFixture: parser, SemanticReferences: "configured LSP only", ConfiguredServers: []LanguageServerState{}, ConfiguredChecks: []string{}, SuggestedServers: []LanguageServerSuggestion{}})
	}
	return result
}

// LanguageSupportMarkdown renders only static runtime inventory. It does not
// inspect PATH, start an LSP/check or read repository/configuration contents.
func LanguageSupportMarkdown() string {
	var out strings.Builder
	entries := RegisteredLanguageSupport()
	out.WriteString("<!-- Generated by go run ./scripts/language-docs. Do not edit this file directly. -->\n\n# Inventário de linguagens do Opcode\n\n")
	fmt.Fprintf(&out, "O runtime registra **%d perfis de sintaxe**, incluindo Go com seu parser padrão.\nA quantidade não mede cobertura semântica nem qualidade geral. Cada perfil local\nprecisa de uma fixture de declarações e chunks do índice em\n`TestLocalLanguageDeclarations`; a suíte verifica essa correspondência.\n\n", len(entries))
	out.WriteString("| Perfil | Reconhecimento | Parser local | Fixture de declarações/índice | Referências semânticas |\n| --- | --- | --- | --- | --- |\n")
	yes := func(value bool) string {
		if value {
			return "Sim"
		}
		return "Não"
	}
	for _, e := range entries {
		parser := yes(e.LocalParser)
		if e.Language == "go" {
			parser = "Go padrão"
		}
		fmt.Fprintf(&out, "| `%s` | %s | %s | %s | LSP configurado |\n", e.Language, yes(e.Recognition), parser, yes(e.ParserFixture))
	}
	out.WriteString("\n## O que o inventário comprova\n\nReconhecer um perfil ou obter declarações locais não resolve tipos, imports,\nreferências, renomes ou chamadas entre arquivos. Esses recursos dependem das\ncapacidades de um LSP configurado e disponível. Não há servidor instalado ou\niniciado por esta documentação. Linguagens ausentes mantêm busca textual e\npodem usar um LSP configurado; extensões reconhecidas não equivalem a parsers.\n\n`get_language_support` e `opcode doctor --languages` mostram a situação local:\nservidores configurados, executáveis encontrados, sugestões e nomes de checks.\nNenhum check é executado pelo inventário; presença de executável não comprova\nque o servidor iniciou ou aceita o projeto. Toolchains, testes e formatação\ncontinuam exigindo ferramentas instaladas e permissões próprias.\n\nOutlines locais têm limite de 256 KiB por fonte, orçamento de parsing e memória;\nfontes incompletas ou fora do suporte podem cair no fallback textual. Vue e\nSvelte extraem scripts JS/TS com linhas da fonte original. Fixtures pequenas não\ngarantem todos os construtos ou versões de uma linguagem.\n\n## Regeneração e verificação\n\n```sh\ngo run ./scripts/language-docs\ngo run ./scripts/language-docs -check\ngo test ./internal/llm/tools -run 'Test(LocalLanguageDeclarations|LanguageSupportDocumentation)'\n```\n\nA geração usa o mesmo inventário do runtime e não acessa projeto, credenciais,\nrede, PATH ou servidores. O teste de drift compara este arquivo byte a byte.\nDetalhes e limites: [recuperação](retrieval-runtime.md) e [ferramentas](code-tools.md).\n")
	return out.String()
}
