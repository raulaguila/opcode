	report := auditReport{findings: []auditFinding{{Severity: "low", Path: "a.go", Line: 90, Code: "return  1 / n", Problem: "divides"}, {Severity: "low", Path: "a.go", Line: 91, Code: "return 2", Problem: "other"}}}
