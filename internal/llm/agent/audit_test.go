type auditProvider struct {
	provider.Provider
	mu      sync.Mutex
	asked   []string
	replies []string
	release chan struct{}
}

func (p *auditProvider) SendMessages(ctx context.Context, history []message.Message, definitions []tools.BaseTool) (*provider.ProviderResponse, error) {
	if len(definitions) > 0 {
		panic("the audit offers no tools")
	}
	if p.release != nil {
		<-ctx.Done()
		return nil, ctx.Err()
	}
	p.mu.Lock()
	defer p.mu.Unlock()
	text := history[len(history)-1].Content().String()
	p.asked = append(p.asked, text)
	reply := "All good here."
	if len(p.replies) > 0 {
		reply, p.replies = p.replies[0], p.replies[1:]
	}
	return &provider.ProviderResponse{Content: reply, FinishReason: message.FinishReasonEndTurn}, nil
}
func (*auditProvider) Model() models.Model {
	return models.Model{ID: "test-model", Provider: models.ProviderOpenAI}
}

func auditProject(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for path, content := range files {
		require.NoError(t, os.MkdirAll(filepath.Dir(filepath.Join(root, path)), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(root, path), []byte(content), 0o644))
	}
	return root
}

func TestAuditPartsCoverEverySourceLineOnce(t *testing.T) {
	big := strings.Repeat("value := compute()\n", 300)
	root := auditProject(t, map[string]string{
		"a/big.go":       big,
		"a/big_test.go":  "package a\n",
		"b/small.py":     "print(1)\n",
		"b/gen.go":       "// Code generated by x. DO NOT EDIT.\npackage b\n",
		"vendor/lib.go":  "package lib\n",
		"web/app.min.js": "x()\n",
		"docs/notes.md":  "not source\n",
	})
	paths := []string{"b/small.py", "a/big.go", "a/big_test.go", "b/gen.go", "vendor/lib.go", "web/app.min.js", "docs/notes.md"}

	parts, unread := auditParts(root, paths, 2048)

	require.Greater(t, len(parts), 1, "a big file spreads over parts")
	require.Equal(t, 4, unread, "tests, generated, vendored and minified code stay out and are counted")
	var body strings.Builder
	for _, part := range parts {
		require.LessOrEqual(t, part.body.Len(), 2200)
		body.WriteString(part.body.String())
	}
	require.Equal(t, 300, strings.Count(body.String(), "value := compute()"))
	require.Contains(t, body.String(), "300: value := compute()", "line numbers survive a split")
	require.Contains(t, parts[len(parts)-1].files, "b/small.py")
}

func TestAuditKeepsOnlyFindingsWhoseQuoteIsAtTheLine(t *testing.T) {
	root := auditProject(t, map[string]string{"a.go": "package a\n\nfunc f(n int) int {\n\treturn 10 / n\n}\n", "b.js": "function f(list) {\n  return list[list.length];\n}\n", "c.py": "# pass the value\n    pass\n"})
	reply := strings.Join([]string{
		"Here is what I found:",
		"- FINDING | high | a.go:4 | `return 10 / n` | divides by zero when n is 0",
		"**FINDING | MEDIUM | a.go:2 | `return 10 / n` | near enough to the line**",
		"FINDING | low | a.go:90 | `return 10 / n` | line does not exist",
		"FINDING | low | a.go:4 | `return 20 / n` | invented code",
		"FINDING | low | ../a.go:4 | `return 10 / n` | outside the project",
		"FINDING | low | a.go:5 | `}` | quote too short to prove anything",
		"FINDING | high | a.go:4 | `return 10 / n` | n is undefined, causing a compile error",
		"FINDING | high | b.js:2 | `return list[list.length];` | returns undefined instead of the last item",
		"FINDING | high | c.py:2 | `pass` | swallows the error",
		"FINDING | high | c.py:1 | `pass` | not the whole line it names",
	}, "\n")

	findings, answered := parseAuditFindings(reply)
	require.True(t, answered)
	require.Len(t, findings, 10)
	var kept []string
	for i := range findings {
		if auditEvidence(root, &findings[i]) {
			kept = append(kept, findings[i].Severity)
		}
	}
	require.Equal(t, []string{"high", "medium", "high", "high"}, kept)

	_, answered = parseAuditFindings("The code looks fine overall.")
	require.False(t, answered, "prose is no answer: the part must not count as read")
	_, answered = parseAuditFindings("**NONE**")
	require.True(t, answered)
}

func TestAuditReadsEveryPartAndSaysWhatItMissed(t *testing.T) {
	a, _, m := steeringAgent(t)
	reviewer := &auditProvider{replies: []string{"FINDING | high | a/one.go:3 | `panic(\"boom\")` | panics on every call"}}
	a.provider = reviewer
	cfg := config.Get()
	previous := cfg.WorkingDir
	cfg.WorkingDir = auditProject(t, map[string]string{
		"a/one.go": "package a\n\nfunc One() { panic(\"boom\") }\n" + strings.Repeat("// padding padding padding padding\n", 1000),
		"b/two.go": "package b\n" + strings.Repeat("// padding padding padding padding\n", 1000),
	})
	t.Cleanup(func() { cfg.WorkingDir = previous })

	events, err := a.Audit(context.Background(), "session")
	require.NoError(t, err)
	result := <-events

	require.False(t, a.IsSessionBusy("session"))
	require.Contains(t, reviewer.asked[0], "=== a/one.go ===", "the code goes to the model, not left for it to find")
	require.Equal(t, "partial", result.Outcome, "prose is no answer")
	text := result.Message.Content().String()
	require.Contains(t, text, "a/one.go:3")
	require.Contains(t, text, "b/two.go", "what was not read is named")
	stored, err := m.List(context.Background(), "session")
	require.NoError(t, err)
	require.Equal(t, "/auditoria", stored[0].Content().String())
	require.Equal(t, text, stored[len(stored)-1].Content().String())
}

func TestAuditReviewDropsOnlyWhatIsClearlyFalse(t *testing.T) {
	a, _, _ := steeringAgent(t)
	source := "package a\n\nfunc One() int { return 1 / zero }\nfunc Two() int { return 2 / zero }\nfunc Six() int { return 6 / zero }\nfunc Ten() int { return 10 / zero }\n"
	reviewer := &auditProvider{replies: []string{
		strings.Join([]string{
			"FINDING | high | a.go:3 | `return 1 / zero` | panics",
			"FINDING | high | a.go:4 | `return 2 / zero` | panics",
			"FINDING | high | a.go:5 | `return 6 / zero` | panics",
			"FINDING | medium | a.go:6 | `return 10 / zero` | panics",
		}, "\n"),
		"NONE",
		"NONE",
		"REAL: zero divides",
		"**FALSE**: zero is a constant one",
		"I am not sure.",
	}}
	a.provider = reviewer
	cfg := config.Get()
	previous := cfg.WorkingDir
	cfg.WorkingDir = auditProject(t, map[string]string{"a.go": source})
	t.Cleanup(func() { cfg.WorkingDir = previous })

	events, err := a.Audit(context.Background(), "session")
	require.NoError(t, err)
	result := <-events

	require.Len(t, reviewer.asked, 6, "three passes, then the three high findings; medium is not reviewed")
	require.Contains(t, reviewer.asked[4], "Claim about a.go:4")
	text := result.Message.Content().String()
	require.Contains(t, text, "a.go:3")
	require.NotContains(t, text, "a.go:4", "clearly false is dropped")
	require.Contains(t, text, "a.go:5", "no verdict keeps the finding")
	require.Contains(t, text, "a.go:6")
	require.Equal(t, "partial", result.Outcome, "a finding without a verdict is said")
}

func TestAuditCancelKeepsWhatWasFound(t *testing.T) {
	a, _, _ := steeringAgent(t)
	a.provider = &auditProvider{release: make(chan struct{})}
	cfg := config.Get()
	previous := cfg.WorkingDir
	cfg.WorkingDir = auditProject(t, map[string]string{"a.go": "package a\n"})
	t.Cleanup(func() { cfg.WorkingDir = previous })

	events, err := a.Audit(context.Background(), "session")
	require.NoError(t, err)
	a.Cancel("session")
	result := <-events

	require.ErrorIs(t, result.Error, ErrRequestCancelled)
	require.Contains(t, result.Message.Content().String(), "a.go")
	require.False(t, a.IsSessionBusy("session"))
}

func TestAuditAsksAgainOnlyAboutWhatChanged(t *testing.T) {
	a, _, _ := steeringAgent(t)
	reviewer := &auditProvider{replies: []string{"NONE", "NONE", "NONE", "NONE", "NONE", "NONE"}}
	a.provider = reviewer
	cfg := config.Get()
	previousDir, previousData := cfg.WorkingDir, cfg.Data.Directory
	cfg.WorkingDir = auditProject(t, map[string]string{"a.go": "package a\n", "b.go": "package b\n"})
	cfg.Data.Directory = t.TempDir()
	t.Cleanup(func() { cfg.WorkingDir, cfg.Data.Directory = previousDir, previousData })

	events, err := a.Audit(context.Background(), "session")
	require.NoError(t, err)
	<-events
	require.Len(t, reviewer.asked, 6)
	require.NoError(t, os.WriteFile(filepath.Join(cfg.WorkingDir, "b.go"), []byte("package b\n\nvar changed = 1\n"), 0o644))

	events, err = a.Audit(context.Background(), "session")
	require.NoError(t, err)
	result := <-events
	require.Len(t, reviewer.asked, 9, "only the changed file goes to the model")
	require.Contains(t, result.Message.Content().String(), "3 replies came from the cache")
}

